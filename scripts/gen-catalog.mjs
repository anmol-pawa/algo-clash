// Regenerates content/gyms/catalog.ts: one entry per problem package (statement embedded, tests lazy-loaded).
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const root = join(process.cwd(), "content", "problems");
const entries = [];
for (const region of readdirSync(root).sort()) {
  for (const id of readdirSync(join(root, region)).sort()) {
    if (existsSync(join(root, region, id, "meta.ts"))) entries.push({ region, id });
  }
}
const ident = (id) => "m_" + id.replace(/-/g, "_");
let out = `// GENERATED by scripts/gen-catalog.mjs (npm run catalog:gen). Do not edit.\n`;
out += `import type { TestCase } from "@/lib/judge/verdict";\nimport type { CatalogProblem } from "./catalogTypes";\n`;
for (const { region, id } of entries) out += `import { meta as ${ident(id)} } from "../problems/${region}/${id}/meta";\n`;
out += `\nexport const problemCatalog: Record<string, CatalogProblem> = {\n`;
for (const { region, id } of entries) {
  const md = readFileSync(join(root, region, id, "problem.md"), "utf8");
  out += `  ${JSON.stringify(id)}: {\n    meta: ${ident(id)},\n    statement: ${JSON.stringify(md)},\n`;
  out += `    loadTests: async () => (await import("../problems/${region}/${id}/tests.json")).default as TestCase[],\n  },\n`;
}
out += `};\n`;
writeFileSync(join(process.cwd(), "content", "gyms", "catalog.ts"), out);
console.log(`catalog: ${entries.length} problems`);
