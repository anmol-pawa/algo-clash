// Usage: node scripts/smoke-modes.mjs <baseUrl>. Scaffolding-mode smoke on /dev/arena: picker, per-mode panels, persistence.
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium, devices } = require("playwright");
const base = process.argv[2] ?? "http://localhost:3000";
const shots = process.env.SHOT_DIR;
const browser = await chromium.launch();
let failed = false;
const fail = (m) => { console.error("FAIL", m); failed = true; };
for (const [name, opts] of [["desktop", { viewport: { width: 1280, height: 800 } }], ["iphone", devices["iPhone 14"]]]) {
  const ctx = await browser.newContext(opts);
  const page = await ctx.newPage();
  const errors = [];
  page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
  page.on("pageerror", (e) => errors.push(String(e)));
  await page.goto(`${base}/dev/arena/`);
  const panel = page.getByTestId("mode-panel");
  await panel.waitFor();
  const pick = (n) => panel.getByRole("radio", { name: n }).click();
  const checked = async (n) => (await panel.getByRole("radio", { name: n }).getAttribute("aria-checked")) === "true";
  if (!(await checked("Standard"))) fail(`${name}: Standard should be the default`);
  if (await page.getByTestId("runs-left").count()) fail(`${name}: Standard must not limit runs`);
  await pick("Interview");
  if (!/Runs left: 6/.test(await page.getByTestId("runs-left").innerText())) fail(`${name}: Interview shows 6 runs`);
  if (await page.getByTestId("hint-panel").count()) fail(`${name}: Interview hides hints`);
  if (shots) await page.screenshot({ path: `${shots}/modes-interview-${name}.png` });
  const own = page.getByTestId("own-tests");
  await own.waitFor();
  if (!/0\/2 passing/.test(await page.getByTestId("own-gate").innerText())) fail(`${name}: own-tests gate starts at 0/2`);
  if (!(await page.getByRole("button", { name: /Submit 🔒/ }).isDisabled())) fail(`${name}: Submit must be locked in Interview`);
  await own.getByRole("button", { name: "+ Add test" }).click();
  await own.getByLabel("Input of test 3").fill("[]");
  if (shots) await page.screenshot({ path: `${shots}/modes-owntests-${name}.png` });
  await pick("Standard");
  if (await page.getByTestId("own-tests").count()) fail(`${name}: Standard has no own-tests gate`);
  if (await page.getByRole("button", { name: /Submit 🔒/ }).count()) fail(`${name}: Standard Submit is open`);
  await pick("Contest");
  await page.getByTestId("timer").waitFor();
  await pick("Guided");
  await page.getByTestId("approach-card").waitFor();
  await page.getByTestId("hint-panel").getByRole("button", { name: /Hints/ }).click();
  await page.getByRole("button", { name: /Reveal Nudge \(free\)/ }).click();
  if (shots) await page.screenshot({ path: `${shots}/modes-guided-${name}.png` });
  await page.reload();
  await page.getByTestId("mode-panel").waitFor();
  await page.waitForTimeout(300);
  if (!(await checked("Guided"))) fail(`${name}: mode did not persist`);
  if (await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)) fail(`${name}: horizontal overflow`);
  if (errors.length) fail(`${name}: console errors ${errors.join(" | ")}`);
  await ctx.close();
}
await browser.close();
if (failed) process.exit(1);
console.log("modes smoke ok");
